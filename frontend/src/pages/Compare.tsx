import { useEffect, useState } from 'react'
import { api } from '../api'

type Results = Awaited<ReturnType<typeof api.results>>

export default function Compare() {
  const [split, setSplit] = useState('test')
  const [data, setData] = useState<Results | null>(null)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => { api.results(split).then(setData).catch(e => setError(String(e))) }, [split])

  if (error) return <p className="error">{error}</p>
  if (!data) return <p className="muted">Loading…</p>
  const cols = data.comparison.length ? Object.keys(data.comparison[0]) : []
  return (
    <section>
      <div className="card">
        <div className="row spread">
          <h1>Compare systems</h1>
          <label>Split
            <select value={split} onChange={e => setSplit(e.target.value)}>
              <option value="test">test (reported)</option>
              <option value="dev">dev</option>
            </select>
          </label>
        </div>
        <p className="muted">
          All numbers are generated by <code>make results</code> from execution-labeled cases; nothing here is typed in by hand.
          {data.meta ? ` Cases: ${String(data.meta.cases)}; LLM providers: ${JSON.stringify(data.meta.llm_providers)}.` : ''}
        </p>
        {data.comparison.length === 0 ? <p className="muted">No results yet: run <code>make results</code>.</p> : (
          <div className="table-wrap">
            <table>
              <thead><tr>{cols.map(c => <th key={c}>{c}</th>)}</tr></thead>
              <tbody>{data.comparison.map((r, i) => <tr key={i}>{cols.map(c => <td key={c}>{String(r[c])}</td>)}</tr>)}</tbody>
            </table>
          </div>
        )}
      </div>
      <div className="figures">
        {data.figures.map(f => (
          <figure key={f} className="card">
            <img src={`/results-files/${f}`} alt={f.replace(/_/g, ' ').replace('.png', '')} loading="lazy" />
            <figcaption>{f}</figcaption>
          </figure>
        ))}
      </div>
    </section>
  )
}
