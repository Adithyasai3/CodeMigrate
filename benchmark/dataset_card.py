"""Generate benchmark/README.md (dataset card) from cases/ and labels/. Numbers are computed.

  python -m benchmark.dataset_card
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main() -> None:
    cases = {json.loads(p.read_text(encoding="utf-8"))["case_id"]: json.loads(
        p.read_text(encoding="utf-8")) for p in sorted((ROOT / "cases").glob("*/case.json"))}
    labels = {p.stem: json.loads(p.read_text(encoding="utf-8"))
              for p in sorted((ROOT / "labels").glob("*.json")) if p.name != "summary.json"}
    status = Counter((c["kind"], labels.get(cid, {}).get("status", "unlabeled"))
                     for cid, c in cases.items())
    usable = {cid for cid, lab in labels.items() if lab["status"] == "ok"}
    split_kind = Counter((cases[c]["split"], cases[c]["kind"]) for c in usable)
    n_labels = Counter()
    by_version = Counter()
    by_evidence = Counter()
    by_type = Counter()
    positives_cases = Counter()
    for cid in usable:
        lab = labels[cid]
        k = cases[cid]["kind"]
        n_labels[(cases[cid]["split"], k)] += len(lab["labels"])
        positives_cases[k] += bool(lab["labels"])
        for item in lab["labels"]:
            by_version[item["first_version"]] += 1
            kinds = {e["kind"] for e in item["evidence"]}
            by_evidence["error (ImportError/AttributeError/TypeError/...)" if "error" in kinds
                        else "Django deprecation warning only"] += 1
            for e in item["evidence"]:
                if e["kind"] == "error":
                    by_type[e["type"]] += 1
                    break
            else:
                by_type[item["evidence"][0]["type"]] += 1
    scored = sum(len(v) for cid in usable for v in labels[cid]["scored_lines"].values())
    ignored = Counter(x["reason"].split(":")[0] for cid in usable
                      for x in labels[cid]["ignored_lines"])
    real = [c for c in cases.values() if c["kind"] == "real"]
    pkgs = defaultdict(lambda: {"files": 0, "usable": 0, "labels": 0})
    for c in real:
        o = c["origin"]
        key = (o["package"], o["version"], o["license"], o["repository"])
        pkgs[key]["files"] += 1
        if c["case_id"] in usable:
            pkgs[key]["usable"] += 1
            pkgs[key]["labels"] += len(labels[c["case_id"]]["labels"])

    md = ["# CodeMigrate benchmark: dataset card", "",
          "_Generated by `python -m benchmark.dataset_card`; every number below is computed "
          "from `benchmark/cases/` and `benchmark/labels/`._", "",
          "## Task", "",
          "Given Python/Django source written for **Django 4.0**, find every line that breaks "
          "(raises) or emits a Django deprecation warning when upgrading to **Django 5.1**.", "",
          "## Ground truth: labels from execution", "",
          "Labels are produced by `benchmark/label_by_execution.py`, **not by CodeMigrate**. "
          "Each case runs under Django 4.0.10, 4.1.13, 4.2.30, 5.0.14 and 5.1.15 (Python "
          "3.10, Docker image `benchmark/harness/Dockerfile`, no network). The driver runs "
          "Python files one statement at a time and records exceptions and "
          "`RemovedInDjango*Warning`s with file and line, plus line coverage.", "",
          "* **positive line**: raises under some 4.1–5.1 release but not under 4.0, or emits "
          "a Django removal warning (removal version > 4.0) under any 4.0–5.1 release",
          "* **ignored line** (not scored): fails already under 4.0, NameError cascade from a "
          "failed import, or failure raised inside another third-party module",
          "* **scored lines**: lines executed under 4.0 (plus labeled spans). Findings on "
          "lines that never ran have no ground truth and are not scored",
          "* **case status**: `ok` (used), `ambiguous` (a Django warning/error could not be "
          "attributed to a line), `silent_injection` (synthetic usage that produced no error "
          "and no warning), `invalid_source` (cannot be set up under 4.0)", "",
          "Ambiguous handling: label lines come from the deepest traceback frame in the case "
          "file, the warning's own location, or, for settings modules and templates, the "
          "line naming the setting/filter in the message. When a class statement fails, the "
          "label moves to the single line inside it that the message names (e.g. "
          "`index_together`). Cases where no line can be attributed are flagged `ambiguous` "
          "and excluded from the main metrics.", "",
          "## Size and distribution", "",
          "| kind | status | cases |", "|---|---|---:|"]
    md += [f"| {k} | {s} | {n} |" for (k, s), n in sorted(status.items())]
    md += ["", "Usable (`ok`) cases by split:", "", "| split | kind | cases | positive labels |",
           "|---|---|---:|---:|"]
    md += [f"| {s} | {k} | {n} | {n_labels[(s, k)]} |" for (s, k), n in sorted(split_kind.items())]
    md += ["", f"Total usable cases: **{len(usable)}**; positive labels: "
           f"**{sum(n_labels.values())}**; scored lines: {scored}; cases with ≥1 positive: "
           f"{dict(positives_cases)}.", "",
           "Labels by first Django version that fails/warns:", "", "| version | labels |",
           "|---|---:|"]
    md += [f"| {v} | {n} |" for v, n in sorted(by_version.items())]
    md += ["", "Labels by evidence:", "", "| evidence | labels |", "|---|---:|"]
    md += [f"| {k} | {n} |" for k, n in by_evidence.most_common()]
    md += ["", "Labels by observed exception/warning type:", "", "| type | labels |", "|---|---:|"]
    md += [f"| {k} | {n} |" for k, n in by_type.most_common()]
    md += ["", "Ignored lines by reason:", "", "| reason | lines |", "|---|---:|"]
    md += [f"| {k} | {n} |" for k, n in ignored.most_common()]
    md += ["", "## Case kinds", "",
           "* **synthetic**: (a) one KB entry's API injected into small code (`kb.usage`, "
           "two styles per entry), (b) hand-written snippets for changes that need a call "
           "(`synthetic_snippets.yaml`), (c) 20 mixed files combining three snippets. The "
           "`intended` field records what the author meant to exercise and is never used as "
           "a label.",
           "* **negative**: clean code and near-misses (replacement APIs, user-defined "
           "lookalikes, safe argument forms) in `negative_snippets.yaml`.",
           "* **real**: files from Django-4.0-era PyPI releases (sdists pinned by version and "
           "sha256 in each `case.json` and `real_provenance.json`), selected by a plain-text "
           "grep for KB names plus randomly sampled other modules of the same package. "
           "Selection never uses the analyzer under evaluation.", "",
           "| package | version | license (PKG-INFO) | files | usable | labels |",
           "|---|---|---|---:|---:|---:|"]
    for (name, ver, lic, repo), v in sorted(pkgs.items()):
        md.append(f"| [{name}]({repo}) | {ver} | {lic} | {v['files']} | {v['usable']} | "
                  f"{v['labels']} |")
    md += ["", "## Splits", "",
           "`dev` (~30%) / `test` (~70%), assigned by hashing a group key with seed 42: all "
           "variants of one API, all files of one package, and each snippet stay in one split. "
           "Development and debugging use `dev`; reported numbers use `test`.", "",
           "## Rebuild", "", "```bash",
           "python -m benchmark.build_benchmark          # cases (downloads pinned sdists)",
           "python -m benchmark.label_by_execution       # Docker; labels/",
           "python -m benchmark.dataset_card             # this file", "```", "",
           "## Limitations", "",
           "* Execution only observes executed paths: usages inside functions that are never "
           "called are unscored. Real-code labels are mostly import-time and class-definition "
           "breakages.",
           "* Behavior changes (same API, different semantics) are not labeled; "
           "`behavior_changed` KB entries are out of scope for this benchmark.",
           "* Some documented removals are silent at runtime (e.g. removed settings are "
           "ignored). By the execution definition they are not breaking; systems that flag "
           "them are counted as false positives unless the earlier release emitted a warning.",
           ""]
    (ROOT / "README.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    print(f"usable={len(usable)} labels={sum(n_labels.values())}")


if __name__ == "__main__":
    main()
